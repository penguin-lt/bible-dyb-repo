"""Catalog of everything in the database — works, translations, sizes, licences.

Prints (and can regenerate) the human-readable inventory in docs/CATALOG.md.
Reads the manifests that ship in the repo, plus the reference manifest which is
small enough to live in git even though the data it describes is a release asset.

    python3 tools/catalog.py                 # summary + full work list
    python3 tools/catalog.py --markdown     # regenerate docs/CATALOG.md
    python3 tools/catalog.py --search greek # find works by name/category
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
REF = os.path.join(ROOT, "bibles", "reference", "data")
TXT = os.path.join(ROOT, "bibles", "text")


def read_csv(path):
    if not os.path.exists(path):
        return []
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def translations():
    return read_csv(os.path.join(TXT, "translations.csv"))


def modules():
    return read_csv(os.path.join(REF, "modules.csv"))


def excluded():
    return read_csv(os.path.join(REF, "modules_excluded.csv"))


def human(n):
    n = float(n)
    for unit in ("", "K", "M", "G"):
        if n < 1000 or unit == "G":
            return f"{n:,.0f}{unit}" if not unit else f"{n:,.1f}{unit}"
        n /= 1000


def summary():
    t, m = translations(), modules()
    tv = sum(int(r["verse_count"]) for r in t)
    me = sum(int(r["entry_count"]) for r in m)
    mc = sum(int(r["char_count"]) for r in m)
    print("DATABASE")
    print(f"  verse corpus     {len(t):3d} translations  {tv:>9,} verses")
    print(f"  reference library{len(m):4d} works         {me:>9,} entries  "
          f"{human(mc)} chars")
    print(f"  total rows       {tv + me:>22,}")
    print()
    by_cat = {}
    for r in m:
        c = by_cat.setdefault(r["category"], [0, 0, 0])
        c[0] += 1
        c[1] += int(r["entry_count"])
        c[2] += int(r["char_count"])
    print("REFERENCE WORKS BY CATEGORY")
    for cat, (n, e, ch) in sorted(by_cat.items(), key=lambda kv: -kv[1][1]):
        print(f"  {cat:12s} {n:3d} works {e:>9,} entries {human(ch):>9} chars")
    print()
    lic = {}
    for r in m:
        lic[r["license"]] = lic.get(r["license"], 0) + 1
    print("REFERENCE LICENCES")
    for k, v in sorted(lic.items(), key=lambda kv: -kv[1]):
        print(f"  {v:3d}  {k}")
    print()
    langs = {}
    for r in m:
        langs[r["language"] or "—"] = langs.get(r["language"] or "—", 0) + 1
    print("REFERENCE LANGUAGES: " +
          ", ".join(f"{k} {v}" for k, v in sorted(langs.items(), key=lambda kv: -kv[1])))


def work_list(pattern=""):
    rows = modules()
    if pattern:
        p = pattern.lower()
        rows = [r for r in rows if p in r["module_name"].lower()
                or p in r["category"].lower() or p in r["module_id"].lower()]
    rows.sort(key=lambda r: (-int(r["entry_count"])))
    print(f"\n{'WORK':34s} {'CATEGORY':12s} {'LANG':5s} {'ENTRIES':>9s} {'CHARS':>9s}  LICENCE")
    for r in rows:
        print(f"{r['module_id'][:33]:34s} {r['category']:12s} {r['language']:5s} "
              f"{int(r['entry_count']):>9,} {human(r['char_count']):>9s}  "
              f"{r['license']}")


def translation_list():
    rows = sorted(translations(), key=lambda r: -int(r["verse_count"]))
    print(f"\n{'ID':14s} {'YEAR':6s} {'VERSES':>9s} {'WORDS':>10s}  NAME")
    for r in rows:
        print(f"{r['translation_id']:14s} {r['year_first_published']:6s} "
              f"{int(r['verse_count']):>9,} {int(r['word_count']):>10,}  "
              f"{r['translation_name'][:58]}")


def markdown():
    t, m = translations(), modules()
    out = ["# Catalog", "",
           "Generated by `tools/catalog.py --markdown`. Every work in the database,",
           "with its size, language and licence.", "",
           f"**{len(t)} translations · {sum(int(r['verse_count']) for r in t):,} verses** "
           f"· **{len(m)} reference works · "
           f"{sum(int(r['entry_count']) for r in m):,} entries**", "",
           "## Bible translations", "",
           "| ID | Name | Year | Verses | Words | Licence |",
           "|---|---|---|---|---|---|"]
    for r in sorted(t, key=lambda r: r["translation_id"]):
        out.append(f"| `{r['translation_id']}` | {r['translation_name'].replace('|','/')} "
                   f"| {r['year_first_published']} | {int(r['verse_count']):,} "
                   f"| {int(r['word_count']):,} | {r['license_type']} |")
    out += ["", "## Reference works", "",
            "| Work | Title | Category | Lang | Entries | Chars | Licence |",
            "|---|---|---|---|---|---|---|"]
    for r in sorted(m, key=lambda r: -int(r["entry_count"])):
        out.append(f"| `{r['module_id']}` | {r['module_name'].replace('|','/')[:74]} "
                   f"| {r['category']} | {r['language']} | {int(r['entry_count']):,} "
                   f"| {int(r['char_count']):,} | {r['license']} |")
    ex = excluded()
    out += ["", "## Examined and excluded", "",
            f"{len(ex)} reference-class modules were inspected and rejected — all on",
            "licence grounds. Full reasons in `bibles/reference/NOT_INCLUDED.md`.", "",
            "| Work | Title | Reason |", "|---|---|---|"]
    for r in sorted(ex, key=lambda r: r["module_id"].lower()):
        out.append(f"| `{r['module_id']}` | {r['module_name'].replace('|','/')[:60]} "
                   f"| {r['reason'][:70]} |")
    return "\n".join(out) + "\n"


def main():
    args = sys.argv[1:]
    if "--markdown" in args:
        md = markdown()
        dest = os.path.join(ROOT, "docs", "CATALOG.md")
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        with open(dest, "w", encoding="utf-8") as fh:
            fh.write(md)
        print("wrote", dest, len(md), "bytes")
        return
    summary()
    if "--translations" in args:
        translation_list()
    if args and args[0] == "--search":
        work_list(args[1] if len(args) > 1 else "")
    elif not args:
        work_list()


if __name__ == "__main__":
    main()
