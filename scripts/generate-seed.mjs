#!/usr/bin/env node
/**
 * Generates db/seed.sql from the bundled demo dataset (demo-data/books).
 *
 * Run:  npm run seed:generate        (writes db/seed.sql)
 * Then paste/run db/seed.sql in the Supabase SQL editor (after db/migration.sql),
 * or:  supabase db push --include-all
 *
 * The script assumes the canonical schema from db/migration.sql
 * (public.books + public.verses).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const booksDir = path.join(root, "demo-data", "books");
const index = JSON.parse(
  fs.readFileSync(path.join(root, "demo-data", "index.json"), "utf-8")
);

const out = [];
out.push("-- Generated by scripts/generate-seed.mjs — do not edit by hand.");
out.push("-- Run db/migration.sql first, then execute this file in the Supabase SQL editor.");
out.push("-- Public-domain King James Version text.");
out.push("set search_path to public;");
out.push("begin;");

// Books
const bookRows = [];
for (const b of index) {
  bookRows.push(
    `  (${b.n}, ${quote(b.name)}, ${quote(b.testament)}, ${b.chapters})`
  );
}
out.push(
  "insert into public.books (id, name, testament, chapters) values\n" +
    bookRows.join(",\n") +
    "\non conflict (id) do update set name=excluded.name, testament=excluded.testament, chapters=excluded.chapters;"
);

// Verses — batched multi-row inserts into a temp staging table then into verses,
// so a partial import is easily retried.
out.push(
  "create temp table _seed_verses (book int, chapter int, verse int, text text) on commit drop;"
);

let values = [];
const rowsPerInsert = 1000;

function flush() {
  if (values.length === 0) return;
  out.push(
    "insert into _seed_verses (book, chapter, verse, text) values\n" +
      values.join(",\n") +
      ";"
  );
  values = [];
}

for (const b of index) {
  const file = path.join(booksDir, `${String(b.n).padStart(2, "0")}.json`);
  const data = JSON.parse(fs.readFileSync(file, "utf-8"));
  data.chapters.forEach((textLines, ci) => {
    const chapter = ci + 1;
    textLines.forEach((text, vi) => {
      values.push(
        `  (${b.n}, ${chapter}, ${vi + 1}, ${quote(text)})`
      );
      if (values.length >= rowsPerInsert) flush();
    });
  });
}
flush();

out.push(`
insert into public.verses (book, chapter, verse, text)
select book, chapter, verse, text from _seed_verses
on conflict (book, chapter, verse) do update set text = excluded.text;

commit;
`);
out.push("");

fs.writeFileSync(path.join(root, "db", "seed.sql"), out.join("\n"));
console.log("Wrote db/seed.sql");

function quote(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}
